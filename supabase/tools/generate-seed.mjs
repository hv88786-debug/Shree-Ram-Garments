// Generates supabase/seed.sql from assets/demo-data.js and the images already used in index.html.
// Usage: npm run seed:generate
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const root = new URL('../../', import.meta.url);
const sandbox = { window: {} };
vm.runInNewContext(readFileSync(new URL('assets/demo-data.js', root), 'utf8'), sandbox);
const { CATEGORIES, PRODUCTS } = sandbox.window.SRG_DEMO;
const html = readFileSync(new URL('index.html', root), 'utf8');

const q = (s) => (s == null ? 'null' : "'" + String(s).replace(/'/g, "''") + "'");
const heroSrc = (html.match(/<img[^>]*fetchpriority="high"[^>]*src="([^"]+)"/) || [])[1];
const logoSrc = (html.match(/<img[^>]*alt="Shree Ram Garments Official Logo"[^>]*src="([^"]+)"/) || [])[1];
const promoSrc = (html.match(/<img[^>]*data-alt="Skilled master artisan[^>]*src="([^"]+)"/) || [])[1];

let o = `-- =============================================================================
-- Shree Ram Garments - demo catalogue seed (generated by supabase/tools/generate-seed.mjs)
-- Run AFTER the three migrations. Safe to run more than once (it skips existing rows).
-- Loads: 5 categories, ${PRODUCTS.length} demo products (names/prices/photos are placeholders),
--        and the current homepage/logo images. No stock rows are invented: add sizes,
--        colours and stock from Admin -> Products.
-- Skip this file if you want to start with an empty catalogue.
-- =============================================================================

`;
o += 'insert into public.categories (slug, name, subcategories, sort_order) values\n';
o += CATEGORIES.map((c, i) => `  (${q(c.id)}, ${q(c.label)}, ${q('{' + c.subs.map((s) => '"' + s.replace(/"/g, '') + '"').join(',') + '}')}::text[], ${i + 1})`).join(',\n');
o += '\non conflict (slug) do nothing;\n\n';

o += 'insert into public.products (slug, name, description, category_id, subcategory, price, is_featured, is_new_arrival, is_active, created_at)\n';
o += 'select v.slug, v.name, v.description, c.id, v.sub, v.price, v.featured, v.is_new, true, v.added::timestamptz\nfrom (values\n';
o += PRODUCTS.map((p) => `  (${q(p.id)}, ${q(p.name)}, ${q(p.description)}, ${q(p.category)}, ${q(p.sub)}, ${Number(p.price)}, ${p.badge === 'Bestseller'}, ${p.badge === 'New Arrival'}, ${q(p.added)})`).join(',\n');
o += '\n) as v(slug, name, description, cat, sub, price, featured, is_new, added)\njoin public.categories c on c.slug = v.cat\non conflict (slug) do nothing;\n\n';

const withImg = PRODUCTS.filter((p) => p.image);
o += 'insert into public.product_images (product_id, url, sort_order)\nselect p.id, v.url, 0\nfrom (values\n';
o += withImg.map((p) => `  (${q(p.id)}, ${q(p.image)})`).join(',\n');
o += '\n) as v(slug, url)\njoin public.products p on p.slug = v.slug\nwhere not exists (select 1 from public.product_images i where i.product_id = p.id);\n\n';

if (heroSrc) o += `update public.homepage_content set hero_image_url = ${q(heroSrc)} where id = 1 and hero_image_url is null;\n`;
if (promoSrc) o += `update public.homepage_content set promo_image_url = ${q(promoSrc)} where id = 1 and promo_image_url is null;\n`;
if (logoSrc) o += `update public.store_settings set logo_url = ${q(logoSrc)} where id = 1 and logo_url is null;\n`;

writeFileSync(new URL('supabase/seed.sql', root), o);
console.log(`seed.sql written: ${CATEGORIES.length} categories, ${PRODUCTS.length} products, ${withImg.length} images`);

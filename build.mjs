// Build: compile Tailwind (public site + admin), bundle the admin app, write runtime
// config from environment variables, and copy the static site into dist/.
import { execSync } from 'node:child_process';
import { cpSync, rmSync, mkdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { build as esbuild } from 'esbuild';

// ---- 1. Environment (Vercel injects process.env; locally we also read a .env file) ----
function loadDotEnv(file = '.env') {
  if (!existsSync(file)) return;
  for (const raw of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = raw.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m || raw.trim().startsWith('#')) continue;
    const v = m[2].replace(/^(['"])(.*)\1$/, '$2');
    if (process.env[m[1]] === undefined) process.env[m[1]] = v;
  }
}
loadDotEnv();

const supabaseUrl = (process.env.SUPABASE_URL || '').trim().replace(/\/+$/, '');
const anonKey = (process.env.SUPABASE_ANON_KEY || '').trim();

function fail(msg) { console.error('\nBUILD STOPPED: ' + msg + '\n'); process.exit(1); }

// Safety net: never ship a secret key to the browser by mistake.
function jwtRole(token) {
  try { return JSON.parse(Buffer.from(token.split('.')[1], 'base64url').toString('utf8')).role; } catch { return null; }
}
if (anonKey) {
  if (anonKey.startsWith('sb_secret_') || jwtRole(anonKey) === 'service_role') {
    fail('SUPABASE_ANON_KEY contains a SECRET key (service_role / sb_secret). Use the public "anon" / "publishable" key instead. Never put the secret key in this project.');
  }
}
if (supabaseUrl && !/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)$/i.test(supabaseUrl) && !/^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(supabaseUrl)) {
  fail('SUPABASE_URL should look like https://YOUR-PROJECT-REF.supabase.co (got: ' + supabaseUrl + ')');
}
const configured = Boolean(supabaseUrl && anonKey);
if (!configured) {
  console.warn('\n! SUPABASE_URL / SUPABASE_ANON_KEY are not set. The public site will show DEMO products and the admin panel cannot sign in.\n  See SETUP.md (copy .env.example to .env for local builds, or add the variables in Vercel).\n');
}

// ---- 2. Clean + copy static files ----
rmSync('dist', { recursive: true, force: true });
mkdirSync('dist/assets', { recursive: true });
mkdirSync('dist/admin', { recursive: true });

for (const f of ['index.html', 'shop.html', 'product.html']) cpSync(f, `dist/${f}`);
cpSync('assets', 'dist/assets', { recursive: true });
for (const f of ['index.html', 'reset.html']) cpSync(`admin/${f}`, `dist/admin/${f}`);

// ---- 3. Runtime config (PUBLIC values only) ----
writeFileSync('dist/assets/config.js',
  '/* Generated by build.mjs - public values only. */\nwindow.SRG_CONFIG = ' +
  JSON.stringify({ supabaseUrl: configured ? supabaseUrl : '', supabaseAnonKey: configured ? anonKey : '' }) + ';\n');

// ---- 4. CSS ----
execSync('npx tailwindcss -c tailwind.config.js -i src/input.css -o dist/assets/styles.css --minify', { stdio: 'inherit' });
execSync('npx tailwindcss -c tailwind.config.js -i src/admin.css -o dist/admin/admin.css --minify', { stdio: 'inherit' });

// ---- 5. Admin app bundle ----
await esbuild({
  entryPoints: { admin: 'src/admin/main.js', reset: 'src/admin/reset.js' },
  outdir: 'dist/admin',
  bundle: true, minify: true, format: 'iife', target: ['es2019'], legalComments: 'none', logLevel: 'warning'
});

for (const f of ['dist/assets/styles.css', 'dist/admin/admin.css', 'dist/admin/admin.js', 'dist/admin/reset.js']) {
  if (!existsSync(f)) { console.error(f + ' was not generated'); process.exit(1); }
}
console.log('Build OK -> dist/' + (configured ? '' : '  (demo mode: Supabase not configured)'));
